import { execFile } from 'node:child_process';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { promisify } from 'node:util';
import { MongooseModule, getConnectionToken } from '@nestjs/mongoose';
import { Test, TestingModule } from '@nestjs/testing';
import { Connection } from 'mongoose';
import { MongoMemoryServer } from 'mongodb-memory-server';
import { ReferenceDataModule } from './reference-data.module';
import {
  createReferenceModels,
  ReferenceModels,
} from './reference-data.models';
import { ReferenceDataService } from './reference-data.service';
import { loadReferenceData, ReferenceData } from './seed/reference-data.loader';
import { seedReferenceData } from './seed/seed-reference-data';

const exec = promisify(execFile);
jest.setTimeout(120000);

describe('reference data with isolated MongoDB and Nest DI', () => {
  let server: MongoMemoryServer;
  let moduleRef: TestingModule;
  let connection: Connection;
  let models: ReferenceModels;
  let service: ReferenceDataService;
  let data: ReferenceData;
  const backend = resolve(__dirname, '../..');
  const cli = resolve(backend, 'dist/reference-data/seed/seed.js');

  beforeAll(async () => {
    // Always compile the actual CLI, including on a fresh clone with no dist directory.
    await exec(
      process.execPath,
      [require.resolve('typescript/bin/tsc'), '-p', 'tsconfig.build.json'],
      { cwd: backend },
    );
    server = await MongoMemoryServer.create({
      instance: { dbName: 'gen12_disposable_test' },
    });
    moduleRef = await Test.createTestingModule({
      imports: [
        MongooseModule.forRoot(server.getUri(), {
          autoIndex: false,
          autoCreate: false,
        }),
        ReferenceDataModule,
      ],
    }).compile();
    await moduleRef.init();
    connection = moduleRef.get<Connection>(getConnectionToken());
    models = createReferenceModels(connection);
    service = moduleRef.get(ReferenceDataService);
    data = await loadReferenceData();
  });

  beforeEach(async () => {
    // The URI is generated by our own disposable server, never ConfigModule/.env.
    await connection.dropDatabase();
  });
  afterEach(() => {
    jest.restoreAllMocks();
  });
  afterAll(async () => {
    await moduleRef?.close();
    await server?.stop();
  });

  it('seeds real datasets twice without duplicates, with unique IDs and timestamps', async () => {
    const first = await seedReferenceData(models, data);
    expect(first.map((r) => r.inserted)).toEqual([7, 8, 8, 8, 8]);
    const original = await models.airports
      .findOne({ iata_code: 'CAI' })
      .lean<{ _id: unknown; createdAt: Date }>();
    expect(original).toMatchObject({
      createdAt: expect.any(Date),
      updatedAt: expect.any(Date),
    });
    const second = await seedReferenceData(models, data);
    expect(second.map((r) => r.inserted)).toEqual([0, 0, 0, 0, 0]);
    expect(second.map((r) => r.matched)).toEqual([7, 8, 8, 8, 8]);
    for (const [name, model] of Object.entries(models)) {
      expect(await model.countDocuments()).toBe(
        data[name as keyof ReferenceData].length,
      );
    }
    const repeated = await models.airports
      .findOne({ iata_code: 'CAI' })
      .lean<{ _id: unknown; createdAt: Date }>();
    expect(repeated?._id).toEqual(original?._id);
    expect(repeated?.createdAt).toEqual(original?.createdAt);
  });

  it('retrieves every reference type by official ID through the exported Nest service', async () => {
    await seedReferenceData(models, data);
    expect(await service.findCountryById('EG')).toEqual(data.countries[0]);
    expect(await service.findCityById('cairo')).toEqual(data.cities[0]);
    expect(await service.findAirportById('CAI')).toEqual(data.airports[0]);
    expect(await service.findAttractionById('att-1')).toEqual(
      data.attractions[0],
    );
    expect(await service.findCurrencyById('EGP')).toEqual({ code: 'EGP' });
    expect(await service.findCountryById('XX')).toBeNull();
    expect(await service.findCityById('unknown')).toBeNull();
    expect(await service.findAirportById('unknown')).toBeNull();
    expect(await service.findAttractionById('unknown')).toBeNull();
    expect(await service.findCurrencyById('unknown')).toBeNull();
    expect(await service.findAirportById('cai')).toBeNull();
    const internal = await models.airports.findOne({ iata_code: 'CAI' });
    expect(await service.findAirportById(String(internal!._id))).toBeNull();
  });

  it('enforces canonical ID uniqueness in all five MongoDB collections', async () => {
    await seedReferenceData(models, data);
    await expect(
      models.countries.create(data.countries[0]),
    ).rejects.toMatchObject({ code: 11000 });
    await expect(models.cities.create(data.cities[0])).rejects.toMatchObject({
      code: 11000,
    });
    await expect(
      models.airports.create(data.airports[0]),
    ).rejects.toMatchObject({ code: 11000 });
    await expect(
      models.attractions.create(data.attractions[0]),
    ).rejects.toMatchObject({ code: 11000 });
    await expect(
      models.currencies.create(data.currencies[0]),
    ).rejects.toMatchObject({ code: 11000 });
  });

  it('reconciles only official fields, preserving IDs, extra fields, extra records and unrelated collections', async () => {
    await seedReferenceData(models, data);
    const original = await models.countries.findOne({ code: 'EG' }).lean();
    await models.countries.collection.updateOne(
      { code: 'EG' },
      { $set: { name: 'Outdated', annotation: 'keep me' } },
    );
    await models.countries.create({
      code: 'ZZ',
      name: 'Retained',
      currency: 'USD',
    });
    await connection.collection('gen12_unrelated').insertOne({ keep: true });
    await seedReferenceData(models, data);
    const restored = await models.countries.collection.findOne({ code: 'EG' });
    expect(restored).toMatchObject({
      _id: original!._id,
      name: 'Egypt',
      annotation: 'keep me',
    });
    expect(await models.countries.countDocuments()).toBe(9);
    expect(
      await connection.collection('gen12_unrelated').countDocuments(),
    ).toBe(1);
  });

  it('replays safely after an interrupted airport batch', async () => {
    const write = models.airports.bulkWrite.bind(models.airports);
    const failure = jest
      .spyOn(models.airports, 'bulkWrite')
      .mockImplementationOnce(async (operations) => {
        await write(operations.slice(0, 1));
        throw new Error('simulated interruption');
      });
    await expect(seedReferenceData(models, data)).rejects.toThrow(
      'simulated interruption',
    );
    expect(await models.countries.countDocuments()).toBe(8);
    expect(await models.cities.countDocuments()).toBe(8);
    expect(await models.airports.countDocuments()).toBe(1);
    expect(await models.attractions.countDocuments()).toBe(0);
    failure.mockRestore();
    const retry = await seedReferenceData(models, data);
    expect(retry.map((r) => r.inserted)).toEqual([0, 0, 0, 7, 8]);
    expect(await models.airports.countDocuments()).toBe(8);
  });

  it('rejects invalid complete input before index creation or data writes', async () => {
    const broken = structuredClone(data);
    broken.attractions[0].city_id = 'missing';
    const indexes = jest.spyOn(models.countries, 'createIndexes');
    await expect(seedReferenceData(models, broken)).rejects.toThrow(
      'unknown city',
    );
    expect(indexes).not.toHaveBeenCalled();
    expect(await connection.db!.listCollections().toArray()).toHaveLength(0);
  });

  it('executes the documented compiled CLI twice, even from a different working directory', async () => {
    const options = {
      cwd: tmpdir(),
      env: { ...process.env, MONGODB_URI: server.getUri() },
    };
    const first = await exec(process.execPath, [cli], options);
    const second = await exec(process.execPath, [cli], options);
    const results = (stdout: string) =>
      stdout
        .trim()
        .split('\n')
        .map((line) => JSON.parse(line) as { inserted: number });
    expect(results(first.stdout).map((r) => r.inserted)).toEqual([
      7, 8, 8, 8, 8,
    ]);
    expect(results(second.stdout).map((r) => r.inserted)).toEqual([
      0, 0, 0, 0, 0,
    ]);
    expect(first.stderr).toBe('');
    expect(second.stderr).toBe('');
  });

  it('CLI fails without writes for missing CSV and hides driver/credential errors', async () => {
    const options = { env: { ...process.env, MONGODB_URI: server.getUri() } };
    await expect(
      exec(
        process.execPath,
        [cli, resolve(tmpdir(), 'gen12-directory-that-does-not-exist')],
        options,
      ),
    ).rejects.toMatchObject({
      code: 1,
      stderr: expect.stringContaining(
        'Countries.csv: cannot read required CSV',
      ),
    });
    expect(await connection.db!.listCollections().toArray()).toHaveLength(0);
    await expect(
      exec(process.execPath, [cli], {
        env: { ...process.env, MONGODB_URI: '' },
      }),
    ).rejects.toMatchObject({
      code: 1,
      stderr: expect.stringContaining('Set MONGODB_URI explicitly'),
    });
    expect(await connection.db!.listCollections().toArray()).toHaveLength(0);
    await expect(
      exec(process.execPath, [cli], {
        env: {
          ...process.env,
          MONGODB_URI: 'mongodb://privateUser:privatePassword@[',
        },
      }),
    ).rejects.toMatchObject({
      code: 1,
      stderr: expect.not.stringMatching(
        /privateUser|privatePassword|mongodb:\/\//,
      ),
    });
  });
});
